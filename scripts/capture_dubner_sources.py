def check(root: Path) -> dict:
    """Verify generated metadata and every retained image without PDF/network access."""
    manifest_path = root / MANIFEST
    try:
        actual = manifest_path.read_bytes()
    except FileNotFoundError as error:
        raise ValueError("Dübner source evidence has not been captured") from error
    expected = expected_manifest()
    if actual != json_bytes(expected):
        raise ValueError("Dübner source evidence manifest differs from reviewed observations")
    if (root / INVENTORY).read_bytes() != json_bytes(inventory()):
        raise ValueError("Generated Dübner boundary inventory differs from reviewed observations")
    for item in expected["files"]:
        path = root / item["path"]
        if not path.is_file() or sha256(path) != item["sha256"]:
            raise ValueError(f"Changed or missing Dübner evidence file: {item['path']}")
    return expected


def resolve_pdf(source: dict, supplied: Path | None, cache: Path) -> Path:
    """Resolve a pinned local input or download it once into the external cache."""
    path = supplied if supplied is not None else cache / source["filename"]
    if not path.is_file():
        if supplied is not None:
            raise ValueError(f"Missing explicitly supplied {source['id']} PDF")
        cache.mkdir(parents=True, exist_ok=True)
        with tempfile.NamedTemporaryFile(dir=cache, prefix=".download-", delete=False) as out:
            temporary = Path(out.name)
            try:
                with urlopen(source["artifact_url"], timeout=60) as response:
                    shutil.copyfileobj(response, out)
            except BaseException:
                temporary.unlink(missing_ok=True)
                raise
        if sha256(temporary) != source["sha256"]:
            temporary.unlink()
            raise ValueError(f"Downloaded {source['id']} PDF does not match its revision pin")
        os.replace(temporary, path)
    if sha256(path) != source["sha256"]:
        raise ValueError(f"Changed {source['id']} source PDF; refusing evidence capture")
    return path


def capture(root: Path, *, toronto_pdf: Path | None = None,
            harvard_pdf: Path | None = None, cache: Path | None = None) -> dict:
    """Stage all validated images before replacing any generated audit output."""
    try:
        import pymupdf
    except ImportError as error:
        raise ValueError(f"Capture requires PyMuPDF=={RENDERER_VERSION}") from error
    if pymupdf.VersionBind != RENDERER_VERSION:
        raise ValueError(f"Capture requires reviewed PyMuPDF {RENDERER_VERSION}")
    cache = cache if cache is not None else Path.home() / ".cache" / "open-greek-corpus" / "dubner-1855"
    supplied = {"toronto": toronto_pdf, "harvard": harvard_pdf}
    paths = {source["id"]: resolve_pdf(source, supplied[source["id"]], cache)
             for source in SOURCES}
    # Keep staging outside the corpus audit directory. An invalid PDF or renderer
    # cannot leave a partly regenerated image set or replace a valid manifest.
    audit_parent = root / AUDIT_DIR.parent
    audit_parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".dubner-evidence-", dir=audit_parent) as temporary:
        stage = Path(temporary)
        staged = []
        for source in SOURCES:
            with pymupdf.open(paths[source["id"]]) as document:
                if len(document) != source["pdf_pages"]:
                    raise ValueError(f"Changed {source['id']} PDF page accounting")
                for source_id, page, digest in RETAINED_IMAGES:
                    if source_id != source["id"]:
                        continue
                    relative = image_path(source_id, page)
                    destination = stage / relative
                    destination.parent.mkdir(parents=True, exist_ok=True)
                    document[page - 1].get_pixmap(
                        matrix=pymupdf.Matrix(RENDER_SCALE, RENDER_SCALE), alpha=False
                    ).save(destination)
                    if sha256(destination) != digest:
                        raise ValueError(f"Rendered source evidence differs: {relative.as_posix()}")
                    staged.append(relative)
        (stage / INVENTORY).write_bytes(json_bytes(inventory()))
        staged.append(INVENTORY)
        # Commit the manifest last, after its complete declared file set exists.
        for relative in staged:
            (root / relative).parent.mkdir(parents=True, exist_ok=True)
            os.replace(stage / relative, root / relative)
        (stage / MANIFEST).write_bytes(json_bytes(expected_manifest()))
        os.replace(stage / MANIFEST, root / MANIFEST)
    return check(root)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--toronto-pdf", type=Path)
    parser.add_argument("--harvard-pdf", type=Path)
    parser.add_argument("--cache", type=Path)
    parser.add_argument("--check", action="store_true",
                        help="Verify retained evidence offline; no renderer required")
    args = parser.parse_args(argv)
    try:
        manifest = check(args.root) if args.check else capture(
            args.root, toronto_pdf=args.toronto_pdf,
            harvard_pdf=args.harvard_pdf, cache=args.cache)
    except (OSError, ValueError) as error:
        parser.exit(1, f"Dübner source evidence: {error}\n")
    print(f"Verified {len(RETAINED_IMAGES)} source images and {len(manifest['sources'])} pinned PDFs")
    return 0


