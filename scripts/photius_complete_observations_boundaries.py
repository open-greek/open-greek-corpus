_CONVENTION = (
    'Expand the printed ου and στ ligatures and the καὶ sign to ordinary Greek Unicode; '
    'retain the current apostrophe and quotation encoding and printed line breaks. '
    'Marginal edition references and line numbers are paratext, and are removed from body readings '
    'while remaining reversible in the exact original row and source scan. '
    'Digital counterpart candidates are diagnostic source observations and do not authorize the scan reading.'
)


def _digital_observations(text, page, sections):
    """Retain every optimal token edge, all ties, and every possible omission."""
    section = f'tlg4040-tlg001-local002-s{page+277}'
    full = sections[section]
    source, local = tokens(full), tokens(text)
    if not local or not source:
        return [], {'section': section, 'tokens': [], 'ambiguous': False, 'aligned': False, 'cost': None}
    aligned = _local_alignment([_key(t['text']) for t in local], [_key(t['text']) for t in source])
    readings, token_records = [], []
    for i, token in enumerate(local):
        span = {key: token[key] for key in ('start', 'end', 'text')}
        possible_gap = aligned['may_be_unaligned'][i]
        token_records.append({**span, 'may_be_unaligned': possible_gap,
                              'counterpart_count': len(aligned['counterparts'][i])})
        for j in aligned['counterparts'][i]:
            readings.append({'kind': 'digital', 'section': section,
                'start': source[j]['start'], 'end': source[j]['end'], 'text': source[j]['text'],
                'review_span': deepcopy(span), 'may_be_unaligned': possible_gap})
    return readings, {'section': section, 'tokens': token_records, 'ambiguous': aligned['ambiguous'],
                      'aligned': aligned['aligned'], 'cost': aligned['cost']}


def _segments(old, reviewed, unknown):
    """Split only unresolved characters; verified regions keep their exact reviewed readings."""
    if not unknown:
        return [(0, len(old), old, reviewed, None)]
    result, a, b = [], 0, 0
    for needle, observed, reason in unknown:
        x, y = old.index(needle, a), reviewed.index(needle, b)
        if x > a:
            result.append((a, x, old[a:x], reviewed[b:y], None))
        result.append((x, x+len(needle), needle, needle, (observed, reason)))
        a, b = x+len(needle), y+len(needle)
    if a < len(old):
        result.append((a, len(old), old[a:], reviewed[b:], None))
    return result


def records(rows, document, crop_png, sections):
    output, cache = [], {}
    for page, number, expected, original, reviewed, crop, fragments, unknown in _SPECS:
        locus = f'helladius_chrestomathia_photius_bekker_v2_{page:04d}.{number}'
        row = rows[locus]
        if row_sha(row) != expected or row['text'] != original:
            raise ValueError(f'Complete review preimage changed: {locus}')
        key = page, crop
        if key not in cache:
            cache[key] = hashlib.sha256(crop_png(document, page, _CROPS[crop])).hexdigest()
        segments, new_offset = [], 0
        for start, end, old, corrected, uncertainty in _segments(original, reviewed, unknown):
            observed = uncertainty[0] if uncertainty else corrected
            digital, alignment = _digital_observations(observed, page, sections)
            segment = {
                'start': start, 'end': end, 'original_text': old, 'corrected_text': corrected,
                'verification': 'uncertain' if uncertainty else 'verified',
                'review_basis': 'direct-scan-inspection', 'reviewed_at': REVIEWED_AT,
                'evidence': 'Direct visual inspection of every character of the recorded printed body range in the pinned Bekker1825 volume2 scan.',
                'scan': {'physical_page': page, 'region': _CROPS[crop], 'image_sha256': cache[key],
                         'observed_text': observed, 'max_side': 3600},
                'readings': digital, 'digital_alignment': alignment,
                'fragments': [], 'transcription_convention': _CONVENTION,
            }
            if uncertainty:
                segment['uncertainty'] = uncertainty[1]
            for f in fragments:
                if new_offset <= f['start'] and f['end'] <= new_offset+len(corrected):
                    segment['fragments'].append({**deepcopy(f), 'start': f['start']-new_offset, 'end': f['end']-new_offset})
            new_offset += len(corrected)
            segments.append(segment)
        if new_offset != len(reviewed):
            raise ValueError(f'Reviewed segment accounting changed: {locus}')
        output.append({'locus': locus, 'original_row_sha256': expected,
                       'status': 'reviewed-with-uncertainty' if unknown else 'reviewed-verified', 'segments': segments})
    return output


def _changed_ranges(original, corrected):
    """Keep admission spans at whole-word boundaries and outside unchanged exclusions."""
    from difflib import SequenceMatcher
    a = list(re.finditer(r"\S+\s*", original))
    b = list(re.finditer(r"\S+\s*", corrected))
    aa, bb = [x.group() for x in a], [x.group() for x in b]
    spans = []
    for tag, i, j, k, l in SequenceMatcher(None, aa, bb, autojunk=False).get_opcodes():
        if tag == 'equal':
            continue
        if i == j or k == l:
            if j < len(a) and l < len(b):
                j += 1
                l += 1
            else:
                i -= 1
                k -= 1
        x, y = a[i].start(), a[j-1].end()
        u, v = b[k].start(), b[l-1].end()
        if spans and x < spans[-1][1]:
            prior = spans.pop()
            x, u = prior[0], prior[2]
        spans.append((x, y, u, v))
    for x, y, u, v in spans:
        # Do not include an unchanged trailing separator in the voted occurrence.
        while y > x and v > u and original[y-1].isspace() and corrected[v-1].isspace():
            y -= 1
            v -= 1
        yield x, y, u, v


def observations():
    """Safe changed word ranges for the existing reversible occurrence layer.

    Digital token counterparts, all ties, and contrary readings are independently
    preserved by records(). No equivalent whole printed digital line is assumed.
    Unresolved source characters and unchanged prior exclusions are not replaced.
    """
    result = []
    for page, number, expected, original, reviewed, crop, fragments, unknown in _SPECS:
        locus = f'helladius_chrestomathia_photius_bekker_v2_{page:04d}.{number}'
        corrected_offset = 0
        for start, end, old, corrected, uncertainty in _segments(original, reviewed, unknown):
            if corrected != old:
                for x, y, u, v in _changed_ranges(old, corrected):
                    before, after = old[x:y], corrected[u:v]
                    if not before or not after or before == after:
                        raise ValueError('A bounded historical occurrence needs two distinct nonempty readings')
                    fragment_sides = [f['side'] for f in fragments
                                      if corrected_offset+u <= f['start'] and f['end'] <= corrected_offset+v]
                    occurrence = sum(original.find(before, 0, q+1) == q
                                     for q in range(start+x))
                    result.append({'locus': locus, 'page': page, 'original_row_sha256': expected,
                        'original_text': before, 'corrected_text': after, 'occurrence': occurrence,
                        'source_region': _CROPS[crop], 'scan_only': True,
                        'qualification': 'Direct source scan reading. Exact digital token counterparts, contrary readings, and all alignment ties are retained separately in the complete-passage review; an equivalent digital whole-line reading is not assumed.',
                        'evidence': 'Direct visual inspection of the complete printed body range, including word forms, accents, punctuation, and printed line fragments.',
                        'source_fragment': {'leading': 'leading' in fragment_sides, 'trailing': 'trailing' in fragment_sides,
                            'qualification': 'Printed incomplete word across retained rows; do not admit this fragment as a complete lexical token.'} if fragment_sides else {},
                        'transcription_convention': _CONVENTION})
            corrected_offset += len(corrected)
    return result
